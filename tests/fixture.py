def sample() -> dict[str, list[list]]:
    return copy.deepcopy(SAMPLE)


def write(data: dict[str, list[list]], path: Path) -> Path:
    wb = Workbook()
    wb.remove(wb.active)
    wb.create_sheet("说明").append(["本文件由测试生成"])
    for name, rows in data.items():
        ws = wb.create_sheet(name)
        for r in rows:
            ws.append(r)
    wb.save(path)
    return path


def set_cell(data: dict, sheet: str, row_id: str, column: str, value) -> None:
    """按编号和列名修改一个单元格。"""
    header = data[sheet][0]
    col = header.index(column)
    for r in data[sheet][1:]:
        if r[0] == row_id:
            r[col] = value
            return
    raise KeyError(row_id)
